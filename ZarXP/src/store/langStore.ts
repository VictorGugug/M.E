export type StringKey = keyof typeof STRINGS.en;

interface LangStore {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: StringKey) => string;
}

export function getInitialLang(): Lang {
  try {
    if (typeof localStorage === "undefined") return "en";
    const v = localStorage.getItem(KEY);
    if (v === "en" || v === "es") return v;
  } catch (err) {
    if (typeof console !== "undefined" && console.warn) {
      console.warn("Could not read language preference from localStorage, falling back to English:", err);
    }
  }
  return "en";
}

export const useLangStore = create<LangStore>((set, get) => ({
  lang: getInitialLang(),
  setLang: (lang) => {
    set({ lang });
    try {
      if (typeof localStorage !== "undefined") {
        localStorage.setItem(KEY, lang);
      }
    } catch (err) {
      if (typeof console !== "undefined" && console.warn) {
        console.warn("Could not persist language preference to localStorage:", err);
      }
    }
  },
  t: (key) => STRINGS[get().lang][key] || key,
}));
